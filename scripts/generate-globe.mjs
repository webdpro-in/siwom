#!/usr/bin/env node
/**
 * Generates the dotted-land data for the shipment globe.
 *
 * Samples points in evenly spaced latitude rows, keeps those that fall on land
 * (Natural Earth 1:50m land, via world-atlas, public domain), and writes a
 * flat integer array of [lat × 10, lon × 10] pairs to data/globe/land-dots.ts.
 * Only land outlines are used: no national boundaries are drawn.
 *
 * Usage: node scripts/generate-globe.mjs [stepDegrees=1.5]
 */
import fs from "node:fs/promises";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const topology = require("world-atlas/land-50m.json");
const land = feature(topology, topology.objects.land);

const step = Number(process.argv[2] ?? 1.5);
const dots = [];
for (let lat = 90 - step / 2; lat > -60; lat -= step) {
  const circumference = Math.cos((lat * Math.PI) / 180);
  const count = Math.max(1, Math.round((360 / step) * circumference));
  // Offset alternate rows by half a step so the pattern does not form columns.
  const offset = (Math.round((90 - lat) / step) % 2) * (180 / count);
  for (let i = 0; i < count; i++) {
    const lon = -180 + (360 * i) / count + offset;
    if (geoContains(land, [lon, lat])) dots.push(Math.round(lat * 10), Math.round(lon * 10));
  }
}

const out = `/* Generated by scripts/generate-globe.mjs from Natural Earth land (public domain). Do not edit. */
/** Flat list of land dots: [lat × 10, lon × 10, lat × 10, lon × 10, …]. ${dots.length / 2} dots at ${step}°. */
export const LAND_DOTS: readonly number[] = [${dots.join(",")}];
`;
await fs.mkdir("data/globe", { recursive: true });
await fs.writeFile("data/globe/land-dots.ts", out);
console.log(`${dots.length / 2} land dots at ${step}° → data/globe/land-dots.ts (${(out.length / 1024).toFixed(0)} KB)`);
